# ───────────────────────── rolling origin ─────────────────────────
def rolling_table(out):
    with open(os.path.join(RESULTS, "rolling_origin_PJM.json"), encoding="utf-8") as f:
        R = json.load(f)
    models = ["Proposed", "PatchTST", "DLinear"]
    origins = R["origins"]
    heads = [f"{o['val_end']} to {o['test_end']}" for o in origins]
    wins = {m: 0 for m in models}
    for o in origins:
        wins[min(models, key=lambda m: o["models"][m]["mean"]["MAPE"])] += 1
    lines = []
    for m in models:
        cells, vals = [], []
        for o in origins:
            mm = o["models"][m]["mean"]["MAPE"]
            ss = o["models"][m]["std"]["MAPE"]
            vals.append(mm)
            best = min(models, key=lambda k: o["models"][k]["mean"]["MAPE"]) == m
            c = f"{mm:.2f} $\\pm$ {ss:.2f}"
            cells.append(f"\\textbf{{{c}}}" if best else c)
        mean = sum(vals) / len(vals)
        lab = "\\textbf{Proposed (CPTB)}" if m == "Proposed" else nm(m)
        lines.append(" & ".join([lab] + cells + [f"{mean:.2f}", str(wins[m])]) + " \\\\")
    dmtxt = []
    for b in ("PatchTST", "DLinear"):
        st = ", ".join(f"{signed(o['dm'][b]['dm_stat'])} ($p = {o['dm'][b]['p_value']:.2f}$)"
                       for o in origins)
        dmtxt.append(f"against {nm(b)}: {st}")
    tex = f"""% generated by scripts/build_latex_tables.py from results/rolling_origin_PJM.json
\\begin{{tabular}}{{@{{}}lrrrrc@{{}}}}
\\toprule
Model & Period 1 & Period 2 & Period 3 & Mean & Periods won \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_rolling.tex"), tex)
    periods = "; ".join(f"period {i + 1}: {h}" for i, h in enumerate(heads))
    w(os.path.join(out, "rolling_dm_note.tex"),
      "% generated by scripts/build_latex_tables.py\n"
      "\\newcommand{\\rollingDMnote}{Test periods (180 days each): " + periods + ". "
      "Diebold--Mariano statistics of the proposed model per period (squared loss, two-seed mean "
      "prediction, negative favours the proposed model), " + "; ".join(dmtxt) + ".}\n")


# ───────────────────────── leakage ─────────────────────────
def leakage_table(out):
    lines, summary = [], {}
    for ds in ("GEFCom2014", "PJM"):
        with open(os.path.join(RESULTS, f"leakage_{ds}.json"), encoding="utf-8") as f:
            J = json.load(f)
        A2, C = J["protocol_A2_global_ceemdan"], J["protocol_C_causal_ceemdan"]
        A, B = J["protocol_A_decompose_then_split"], J["protocol_B_causal"]
        nd = 2 if ds == "GEFCom2014" else 0

        def row(lab, P):
            cells = [f"{P['MAPE']:.2f}", f"{P['MAE']:.{nd}f}", f"{P['RMSE']:.{nd}f}", f"{P['R2']:.3f}"]
            return " & ".join([lab] + cells) + " \\\\"

        def eff(P1, P2):
            return {k: 100.0 * (P2[k] - P1[k]) / P2[k] for k in ("MAPE", "MAE", "RMSE")}

        em, eu = eff(A2, C), eff(A, B)
        summary[ds] = {"matched": {k: round(v, 1) for k, v in em.items()},
                       "unmatched": {k: round(v, 1) for k, v in eu.items()},
                       "fallback_windows": C.get("_fallback_windows", 0)}
        lines.append(f"\\multicolumn{{5}}{{@{{}}l}}{{\\emph{{{ds}}}}} \\\\")
        lines.append(row("\\quad A2: global CEEMDAN, then split (invalid)", A2))
        lines.append(row("\\quad C: windowed CEEMDAN, causal (valid)", C))
        lines.append(" & ".join(["\\quad Apparent reduction, A2 relative to C (\\%)",
                                 f"\\textbf{{{em['MAPE']:.1f}}}", f"\\textbf{{{em['MAE']:.1f}}}",
                                 f"\\textbf{{{em['RMSE']:.1f}}}", "---"]) + " \\\\")
        lines.append("\\addlinespace[2pt]")
        lines.append(row("\\quad A: global CEEMDAN, one ridge per component", A))
        lines.append(row("\\quad B: causal moving-average split, one ridge", B))
        lines.append(" & ".join(["\\quad Apparent reduction, A relative to B (\\%)",
                                 f"{eu['MAPE']:.1f}", f"{eu['MAE']:.1f}", f"{eu['RMSE']:.1f}", "---"]) + " \\\\")
        if ds == "GEFCom2014":
            lines.append("\\midrule")
    tex = f"""% generated by scripts/build_latex_tables.py from results/leakage_GEFCom2014.json and results/leakage_PJM.json
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
Protocol & MAPE (\\%) & MAE & RMSE & $R^2$ \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_leakage.tex"), tex)
    print("leakage effects:", json.dumps(summary))



#!/usr/bin/env python3
"""Emit every numeric table of the LaTeX manuscript from the released result
files, so that no number in a table is typed by hand.

    python scripts/build_latex_tables.py [--out ../latex/tables]

Inputs (all under results/): Table3/4/5 CSVs (day-ahead results), Table6
ablation CSVs, Table7 efficiency CSV, summary_v4.json (DM tests, ensembles),
rolling_origin_PJM.json, leakage_*.json, covskip_selection.json, mcs_v4.json.
"""
import argparse
import csv

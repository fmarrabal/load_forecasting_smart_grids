import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
RESULTS = os.path.join(CODE, "results")
DEFAULT_OUT = os.path.join(os.path.dirname(CODE), "latex", "tables")

DS = ["GEFCom2014", "PJM", "AEMO"]
NAME = {"Proposed": "Proposed (CPTB)", "SeasonalNaive": "Seasonal na\\\"ive",
        "CNN_LSTM": "CNN--LSTM", "CNN-LSTM": "CNN--LSTM",
        "GRU_TCN_Attention": "GRU--TCN--Attention",
        "GRU-TCN-Attention": "GRU--TCN--Attention",
        "GRU-TCN-Att.": "GRU--TCN--Att."}
CANON = ["Proposed", "TiDE", "PatchTST", "DLinear", "TCN", "Transformer", "GRU",
         "LSTM", "BiLSTM", "CNN_LSTM", "GRU_TCN_Attention", "XGBoost", "LightGBM",
         "ARIMA", "SeasonalNaive"]


def nm(s):
    return NAME.get(s, s.replace("_", "-"))


def read_csv(path):
    with open(path, encoding="utf-8") as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def split_pm(cell):
    m = re.match(r"^\s*([-−+]?[\d.,]+)\s*±\s*([\d.,]+)\s*$", cell)
    if not m:
        return cell.strip(), None
    return m.group(1), m.group(2)


def fnum(x):
    return float(str(x).replace("−", "-").replace(",", ""))


def tex_num(x):
    x = str(x).replace("−", "-")
    return "$-$" + x[1:] if x.startswith("-") else x


def tex_pm(mean, std, bold=False):
    s = f"{tex_num(mean)} $\\pm$ {std}" if std is not None else tex_num(mean)
    return f"\\textbf{{{s}}}" if bold else s


def sig(name):
    m = re.match(r"^(.*?)\s*(\*+)$", name)
    return (m.group(1), m.group(2)) if m else (name, "")


def signed(x, nd=2):
    s = f"{x:+.{nd}f}"
    return ("$+$" if s[0] == "+" else "$-$") + s[1:]


def w(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(path))


# ───────────────────────── day-ahead results ─────────────────────────
def results_tables(out):
    files = {"GEFCom2014": "Table3_GEFCom2014.csv", "PJM": "Table4_PJM.csv",
             "AEMO": "Table5_AEMO.csv"}
    units = {"GEFCom2014": "", "PJM": " (MW)", "AEMO": " (MW)"}
    for ds in DS:
        hdr, rows = read_csv(os.path.join(RESULTS, files[ds]))
        parsed = []
        for r in rows:
            name, star = sig(r[0])
            parsed.append((name, star, [split_pm(c) for c in r[1:]]))
        best = []
        for j in range(5):
            vals = [fnum(p[2][j][0]) for p in parsed]
            best.append(max(range(len(vals)), key=lambda i: vals[i]) if j == 3
                        else min(range(len(vals)), key=lambda i: vals[i]))
        # MW-valued MAE/RMSE (PJM, AEMO) are shown to one decimal: the second
        # decimal of a megawatt figure carries no information and widens the table
        def fmt(j, m, s):
            if ds != "GEFCom2014" and j in (0, 1):
                m = f"{fnum(m):.1f}"
                s = None if s is None else f"{fnum(s):.1f}"
            return m, s

        lines = []
        for i, (name, star, cells) in enumerate(parsed):
            label = nm(name) + (f"$^{{{star}}}$" if star else "")
            if name == "Proposed":
                label = f"\\textbf{{{label}}}"
            cs = [tex_pm(*fmt(j, m, s), bold=(best[j] == i)) for j, (m, s) in enumerate(cells)]
            lines.append(" & ".join([label] + cs) + " \\\\")
        body = "\n".join(lines)
        tex = f"""% generated by scripts/build_latex_tables.py from results/{files[ds]}
\\begin{{tabular}}{{@{{}}lrrrrr@{{}}}}
\\toprule
Model & MAE{units[ds]} & RMSE{units[ds]} & MAPE (\\%) & $R^2$ & sMAPE (\\%) \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""
        w(os.path.join(out, f"tab_results_{ds}.tex"), tex)



def ablation_table(out, summary):
    data = {}
    for ds, fn in (("GEFCom2014", "Table6_ablation_GEFCom2014.csv"),
                   ("AEMO", "Table6_ablation_AEMO.csv")):
        hdr, rows = read_csv(os.path.join(RESULTS, fn))
        data[ds] = {r[0]: [split_pm(c) for c in r[1:]] for r in rows}
    # the contrast is computed from the unrounded five-seed means and spreads,
    # so that it agrees with the figures, which read the same file
    raw = summary["ablations"]
    n_seeds = 5
    lines, resolved = [], {}
    for key, label in ABL_ORDER:
        cells = []
        for ds in ("GEFCom2014", "AEMO"):
            full = data[ds]["Full (Proposed)"][2]
            if key not in data[ds]:
                cells += ["n/a", "n/a"]
                continue
            m, s = data[ds][key][2]
            mape = f"{m} $\\pm$ {s}"
            if key == "Full (Proposed)":
                cells += [mape, "---"]
                continue
            rm, rs = raw[ds][key]["mean"]["MAPE"], raw[ds][key]["std"]["MAPE"]
            fm, fstd = raw[ds]["Full (Proposed)"]["mean"]["MAPE"], raw[ds]["Full (Proposed)"]["std"]["MAPE"]
            d = rm - fm
            se = ((rs ** 2 + fstd ** 2) / n_seeds) ** 0.5
            res = abs(d) >= 2 * se
            resolved[(ds, key)] = (d, se, res)
            dtxt = f"{signed(d)} $\\pm$ {se:.2f}"
            cells += [mape, f"\\textbf{{{dtxt}}}" if res else dtxt]
        lines.append(" & ".join([label] + cells) + " \\\\")
    groups = [1, 4, 7, 11]
    body = []
    for i, ln in enumerate(lines):
        if i in groups:
            body.append("\\addlinespace[3pt]")
        body.append(ln)
    tex = f"""% generated by scripts/build_latex_tables.py from results/Table6_ablation_*.csv
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
 & \\multicolumn{{2}}{{c}}{{GEFCom2014 (covariate-rich)}} & \\multicolumn{{2}}{{c}}{{AEMO (univariate)}} \\\\
\\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-5}}
Variant & MAPE (\\%) & $\\Delta$MAPE (pp) & MAPE (\\%) & $\\Delta$MAPE (pp) \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_ablation.tex"), tex)
    for ds, fn in (("GEFCom2014", "Table6_ablation_GEFCom2014.csv"),
                   ("AEMO", "Table6_ablation_AEMO.csv")):
        hdr, rows = read_csv(os.path.join(RESULTS, fn))
        lab = dict(ABL_ORDER)
        ordered = [r for k, _ in ABL_ORDER for r in rows if r[0] == k]
        ls = [" & ".join([lab[r[0]]] + [tex_pm(*split_pm(c)) for c in r[1:]]) + " \\\\"
              for r in ordered]
        tex = f"""% generated by scripts/build_latex_tables.py from results/{fn}
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
Variant & MAE & RMSE & MAPE (\\%) & $R^2$ \\\\
\\midrule
{chr(10).join(ls)}
\\bottomrule
\\end{{tabular}}
"""
        w(os.path.join(out, f"tab_ablation_full_{ds}.tex"), tex)
    print("ablation effects (|d| >= 2 SE marked RESOLVED):")
    for (ds, k), (d, se, r) in resolved.items():
        print(f"   {ds:11s} {k:36s} d={d:+.2f} se={se:.3f} t={d/se:+.2f} {'RESOLVED' if r else ''}")


# ───────────────────────── Diebold–Mariano ─────────────────────────
def holm(pvals):
    idx = sorted(range(len(pvals)), key=lambda i: pvals[i])
    m = len(pvals)
    adj = [0.0] * m
    running = 0.0
    for rank, i in enumerate(idx):
        val = min(1.0, (m - rank) * pvals[i])
        running = max(running, val)
        adj[i] = running
    return adj


def fp(p):
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def dm_table(out, summary):
    base = [m for m in CANON if m != "Proposed"]
    cells, minpos = {}, {}
    for ds in DS:
        dm = summary["results"][ds]["_dm_multiseed"]
        p_mae = holm([dm[b]["p_value_mae"] for b in base])
        for i, b in enumerate(base):
            e = dm[b]
            cells[(ds, b)] = (e["dm_stat"], e["p_holm"], e["dm_mae"], p_mae[i])
        pos = [(round(dm[b]["p_holm"], 3), b) for b in base if dm[b]["dm_stat"] > 0]
        minpos[ds] = min(pos) if pos else None
    order = sorted(base, key=lambda b: cells[("GEFCom2014", b)][0])
    panels = []
    for lname, si in (("Squared-error loss", 0), ("Absolute-error loss", 2)):
        rows = [f"\\multicolumn{{4}}{{@{{}}l}}{{\\emph{{{lname}}}}} \\\\"]
        for b in order:
            row = [nm(b)]
            for ds in DS:
                c = cells[(ds, b)]
                row.append(f"{signed(c[si])} ({fp(c[si + 1])})")
            rows.append(" & ".join(row) + " \\\\")
        panels.append("\n".join(rows))
    tex = f"""% generated by scripts/build_latex_tables.py from results/summary_v4.json (_dm_multiseed)
\\begin{{tabular}}{{@{{}}lccc@{{}}}}
\\toprule
Baseline & GEFCom2014 ($n=259$) & PJM ($n=902$) & AEMO ($n=274$) \\\\
\\midrule
{panels[0]}
\\midrule
{panels[1]}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_dm.tex"), tex)
    print("smallest Holm p among baselines with positive DM (baseline ahead):", minpos)
    for ds in DS:
        dm = summary["results"][ds]["_dm_multiseed"]
        p_mae = holm([dm[b]["p_value_mae"] for b in base])
        neg = [b for b in base if dm[b]["dm_mae"] < 0]
        sig_mae = [(b, round(p_mae[i], 3)) for i, b in enumerate(base)
                   if dm[b]["dm_mae"] < 0 and p_mae[i] < 0.05]
        print(f"  {ds}: negative DM(abs) vs {len(neg)}/14; significant (Holm) under abs loss: {sig_mae}")



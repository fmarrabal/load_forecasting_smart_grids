def ensemble_table(out, summary):
    ranks = {}
    for ds, fn in (("GEFCom2014", "Table8b_ensembles_GEFCom2014.csv"),
                   ("PJM", "Table8b_ensembles_PJM.csv"), ("AEMO", "Table8b_ensembles_AEMO.csv")):
        hdr, rows = read_csv(os.path.join(RESULTS, fn))
        dm = summary["results"][ds]["_dm_ensemble"]
        lst = []
        for r in rows:
            model = r[1].replace("-Ens", "")
            key = model.replace("-", "_") + "-Ens"
            star = ""
            if key in dm and dm[key]["dm_stat"] < 0:
                star = "**" if dm[key]["p_holm"] < 0.01 else "*" if dm[key]["p_holm"] < 0.05 else ""
            lst.append((model, r[4], star))
        ranks[ds] = lst
        pos = sorted((round(dm[k]["p_holm"], 3), k) for k in dm if dm[k]["dm_stat"] > 0)
        print(f"ensemble {ds}: baseline ensembles ahead of the proposed ensemble (p_holm, name): {pos}")
    n = max(len(v) for v in ranks.values())
    lines = []
    for i in range(n):
        row = [str(i + 1)]
        for ds in DS:
            model, mape, star = ranks[ds][i]
            lab = nm(model.replace("GRU-TCN-Attention", "GRU_TCN_Attention").replace("CNN-LSTM", "CNN_LSTM"))
            if model == "Proposed":
                lab = "\\textbf{Proposed}"
            row += [lab + (f"$^{{{star}}}$" if star else ""), mape]
        lines.append(" & ".join(row) + " \\\\")
    tex = f"""% generated by scripts/build_latex_tables.py from results/Table8b_ensembles_*.csv and summary_v4.json (_dm_ensemble)
\\begin{{tabular}}{{@{{}}clrlrlr@{{}}}}
\\toprule
 & \\multicolumn{{2}}{{c}}{{GEFCom2014}} & \\multicolumn{{2}}{{c}}{{PJM}} & \\multicolumn{{2}}{{c}}{{AEMO}} \\\\
\\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-5}} \\cmidrule(lr){{6-7}}
Rank & Ensemble & MAPE & Ensemble & MAPE & Ensemble & MAPE \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_ensembles.tex"), tex)



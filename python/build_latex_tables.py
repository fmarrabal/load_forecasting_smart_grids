# ───────────────────────── model confidence set ─────────────────────────
def mcs_table(out):
    path = os.path.join(RESULTS, "mcs_v4.json")
    if not os.path.exists(path):
        print("mcs_v4.json missing; skipping MCS table")
        return
    with open(path, encoding="utf-8") as f:
        J = json.load(f)
    lines = []
    for m in CANON:
        row = ["\\textbf{Proposed (CPTB)}" if m == "Proposed" else nm(m)]
        for ds in DS:
            for loss in ("mse", "mae"):
                pm = J["datasets"][ds][loss]["p_mcs"]
                if m not in pm:
                    row.append("excl.")
                    continue
                p = pm[m]
                c = f"{p:.2f}" if p >= 0.005 else "$<$0.01"
                row.append(f"\\textbf{{{c}}}" if p >= 0.10 else c)
        lines.append(" & ".join(row) + " \\\\")
    tex = f"""% generated by scripts/build_latex_tables.py from results/mcs_v4.json
\\begin{{tabular}}{{@{{}}lcccccc@{{}}}}
\\toprule
 & \\multicolumn{{2}}{{c}}{{GEFCom2014}} & \\multicolumn{{2}}{{c}}{{PJM}} & \\multicolumn{{2}}{{c}}{{AEMO}} \\\\
\\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-5}} \\cmidrule(lr){{6-7}}
Model & squared & absolute & squared & absolute & squared & absolute \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
"""
    w(os.path.join(out, "tab_mcs.tex"), tex)
    for ds in DS:
        for loss in ("mse", "mae"):
            r = J["datasets"][ds][loss]
            print(f"MCS90 {ds} [{loss}] ({len(r['mcs_90'])} models): {r['mcs_90']}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(RESULTS, "summary_v4.json"), encoding="utf-8") as f:
        summary = json.load(f)
    results_tables(a.out)
    ablation_table(a.out, summary)
    dm_table(a.out, summary)
    ensemble_table(a.out, summary)
    efficiency_table(a.out)
    rolling_table(a.out)
    leakage_table(a.out)
    covskip_table(a.out)
    mcs_table(a.out)


if __name__ == "__main__":
    main()
